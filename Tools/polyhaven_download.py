#!/usr/bin/env python3
"""Download the game's CC0 Poly Haven texture sets into Assets/Resources/Textures/PH.

Each set becomes <Key>_A.jpg (albedo, sRGB), <Key>_N.jpg (OpenGL normal) and <Key>_ORM.jpg
(R occlusion, G roughness, B metal = Poly Haven "arm"). Albedo and normal use 2K for textures that
tile over 2.5 m or more and 1K otherwise; ORM is always 1K. The real-world size of every set is
written to docs/TEXTURES.json and Assets/Scripts/RailTextures.cs (tile size and mean linear albedo, used to
tint grey textures to a target colour).
Usage: python3 Tools/polyhaven_download.py [Key ...]   (no keys = all sets; existing files are only re-measured)
"""
import io
import json
import ssl
import sys
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Assets/Resources/Textures/PH"
SETS = {
    "Ballast": "rocks_ground_01",
    "Paving": "large_square_pattern_01",
    "Concrete": "brushed_concrete",
    "Asphalt": "asphalt_02",
    "RailSteel": "rusty_metal_02",
    "Brick": "red_brick_03",
    "Plaster": "painted_plaster_wall",
    "PanelConcrete": "concrete_wall_008",
    "RoofTiles": "clay_roof_tiles_02",
    "Corrugated": "corrugated_iron_02",
    "MetalPlate": "metal_plate_02",
    "TreadPlate": "metal_grate_rusty",
    "Grass": "leafy_grass",
    "Planks": "weathered_planks",
    "SiloConcrete": "concrete_panels",
}
HEADERS = {"User-Agent": "SuperCigo-texture-fetch"}
CONTEXT = ssl.create_default_context(cafile="/etc/ssl/cert.pem" if Path("/etc/ssl/cert.pem").exists() else None)


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), context=CONTEXT, timeout=90) as response:
        return response.read()


def save(data, path, size, quality=90):
    image = Image.open(io.BytesIO(data)).convert("RGB")
    if image.width != size:
        image = image.resize((size, size), Image.LANCZOS)
    image.save(path, "JPEG", quality=quality, optimize=True)


def mean_linear(path):
    image = Image.open(path).convert("RGB").resize((128, 128), Image.LANCZOS)
    total = 0.0
    data = image.tobytes()
    for i in range(0, len(data), 3):
        r, g, b = data[i], data[i + 1], data[i + 2]
        lin = [(c / 255) / 12.92 if c <= 10 else (((c / 255) + .055) / 1.055) ** 2.4 for c in (r, g, b)]
        total += .2126 * lin[0] + .7152 * lin[1] + .0722 * lin[2]
    return total / (128 * 128)


def write_catalog(catalog):
    lines = ["// Generated by Tools/polyhaven_download.py from Poly Haven (CC0). Do not edit by hand.",
             "namespace CeskeDrahy", "{",
             "    /// <summary>Texture sets in Resources/Textures/PH: real-world tile size and mean linear albedo luminance.</summary>",
             "    public static class RailTextures", "    {",
             "        public static float Tile(string key)", "        {", "            switch(key)", "            {"]
    for key, entry in catalog.items():
        lines.append(f'                case "{key}":return {entry["tileMetres"]}f;')
    lines += ["                default:return 2f;", "            }", "        }",
              "        public static float MeanLuminance(string key)", "        {", "            switch(key)", "            {"]
    for key, entry in catalog.items():
        lines.append(f'                case "{key}":return {entry["meanLinear"]:.4f}f;')
    lines += ["                default:return .2f;", "            }", "        }", "    }", "}", ""]
    (ROOT / "Assets/Scripts/RailTextures.cs").write_text("\n".join(lines), encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    assets = json.loads(get("https://api.polyhaven.com/assets?t=textures"))
    catalog = {}
    only = set(sys.argv[1:])
    for key, slug in SETS.items():
        info = assets[slug]
        tile = round(info["dimensions"][0] / 1000, 3)
        res = "2k" if tile >= 2.5 else "1k"
        catalog[key] = {"slug": slug, "name": info["name"], "tileMetres": tile, "resolution": res,
                        "url": "https://polyhaven.com/a/" + slug, "license": "CC0"}
        if (not only and not (OUT / f"{key}_A.jpg").exists()) or key in only:
            fetch(key, slug, res)
        catalog[key]["meanLinear"] = round(mean_linear(OUT / f"{key}_A.jpg"), 4)
        print(f"{key:14} {slug:26} tile {tile:5} m  {res}  mean {catalog[key]['meanLinear']}")
    (ROOT / "docs/TEXTURES.json").write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_catalog(catalog)


def fetch(key, slug, res):
    files = json.loads(get("https://api.polyhaven.com/files/" + slug))
    size = 2048 if res == "2k" else 1024
    save(get(files["Diffuse"][res]["jpg"]["url"]), OUT / f"{key}_A.jpg", size)
    save(get(files["nor_gl"][res]["jpg"]["url"]), OUT / f"{key}_N.jpg", size, 95)
    save(get(files["arm"]["1k"]["jpg"]["url"]), OUT / f"{key}_ORM.jpg", 1024)


if __name__ == "__main__":
    main()
